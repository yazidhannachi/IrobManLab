#!/usr/bin/env python3
"""Generate assembly constants from the supplied, unchanged millimetre STL.

Authoring only: python -m pip install numpy trimesh
Run from any directory. ROS/Gazebo need only the checked-in generated xacro.
The nominal hand flange clip spans z=0..8.5 mm; its bore is at x=-25 mm.
The lower lip overlaps the wrist CAD; see README.md for the modeled discrepancy.
The camera seat is 3 mm thick, tilted 50 degrees, with 36 mm hole spacing.
These are nominal CAD placements, not measured hand-eye calibration.
"""
from pathlib import Path
import hashlib
import trimesh

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / 'ros2_ws/src/franka_sim_bringup'
SOURCE_SHA256 = '1f9f598ac1c1de75cf86ed02649a8cf0e4deefbc6ae22dada8466f7bbce9c672'


def main():
    source = PACKAGE / 'meshes/zedminixmount.stl'
    assert hashlib.sha256(source.read_bytes()).hexdigest() == SOURCE_SHA256
    mount = trimesh.load_mesh(source)
    assert mount.is_watertight and mount.volume > 0
    mount.apply_scale(0.001)
    mount.density = 1240  # solid PLA estimate; weigh the printed part for hardware
    inertia = mount.moment_inertia
    com = ' '.join(f'{v:.9f}' for v in mount.center_mass)
    # Centre of the three bores on the upper seating plane, in STL coordinates.
    camera_xyz = '0.0656689 0.0400000 -0.0141432'
    text = f'''<?xml version="1.0"?>
<!-- Generated by cad/zed_x_mini/prepare_mount.py. Source STL is unchanged. -->
<robot xmlns:xacro="http://www.ros.org/wiki/xacro">
  <xacro:property name="zed_x_mini_mount_xyz" value="-0.025 0.040 0.017"/>
  <xacro:property name="zed_x_mini_xyz" value="{camera_xyz}"/>
  <xacro:property name="zed_x_mini_pitch" value="${{-50*pi/180}}"/>
  <xacro:macro name="zed_x_mini_mount_inertial">
    <inertial>
      <mass value="{mount.mass:.9f}"/>
      <origin xyz="{com}"/>
      <inertia ixx="{inertia[0,0]:.12f}" ixy="{inertia[0,1]:.12f}" ixz="{inertia[0,2]:.12f}"
               iyy="{inertia[1,1]:.12f}" iyz="{inertia[1,2]:.12f}" izz="{inertia[2,2]:.12f}"/>
    </inertial>
  </xacro:macro>
</robot>
'''
    (PACKAGE / 'urdf/zed_x_mini_mount.generated.xacro').write_text(text)
    print(f'Closed mount: {mount.mass * 1000:.2f} g solid PLA estimate')


if __name__ == '__main__':
    main()
